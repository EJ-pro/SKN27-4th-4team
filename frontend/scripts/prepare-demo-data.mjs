import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const scriptDir = path.dirname(fileURLToPath(import.meta.url))
const frontendDir = path.resolve(scriptDir, '..')
const projectDir = path.resolve(frontendDir, '..')
const sourcePath = path.join(projectDir, 'backend', 'data', 'planfit_exercises_enriched.json')
const videosDir = path.join(frontendDir, 'public', 'videos')
const outputPath = path.join(frontendDir, 'src', 'data', 'generatedExercises.js')

const source = JSON.parse(fs.readFileSync(sourcePath, 'utf8'))
let localVideoCount = 0
const videoIndex = new Map()
const globalVideoIndex = new Map()

for (const categoryEntry of fs.readdirSync(videosDir, { withFileTypes: true })) {
  if (!categoryEntry.isDirectory()) continue
  const categoryDir = path.join(videosDir, categoryEntry.name)
  for (const fileName of fs.readdirSync(categoryDir)) {
    if (!fileName.toLowerCase().endsWith('.mp4')) continue
    const id = fileName.split('_', 1)[0]
    videoIndex.set(`${categoryEntry.name}:${id}`, fileName)
    if (!globalVideoIndex.has(id)) {
      globalVideoIndex.set(id, { category: categoryEntry.name, fileName })
    }
  }
}

const exercises = source.map((exercise) => {
  const id = Number(exercise.id ?? exercise.exercise_id)
  const category = String(exercise.category || '').trim()
  const name = String(exercise.name_kor || '').trim()
  const relativeVideoPath = path.join(category, `${id}_${name}.mp4`)
  const exactVideoExists = fs.existsSync(path.join(videosDir, relativeVideoPath))
  const indexedVideoName = videoIndex.get(`${category}:${id}`)
  const globalVideo = globalVideoIndex.get(String(id))
  const localVideo = exactVideoExists
    ? { category, fileName: `${id}_${name}.mp4` }
    : indexedVideoName
      ? { category, fileName: indexedVideoName }
      : globalVideo
  const hasLocalVideo = Boolean(localVideo)

  if (hasLocalVideo) localVideoCount += 1

  return {
    ...exercise,
    id,
    video_url: hasLocalVideo
      ? `/videos/${localVideo.category}/${localVideo.fileName}`
      : String(exercise.video_url || ''),
  }
})

const contents = [
  '// Auto-generated by scripts/prepare-demo-data.mjs. Do not edit manually.',
  `export const generatedExercises = ${JSON.stringify(exercises, null, 2)}`,
  '',
].join('\n')

fs.writeFileSync(outputPath, contents, 'utf8')
console.log(`Prepared ${exercises.length} exercises (${localVideoCount} local videos).`)
